function detectLang() {
  const saved = localStorage.getItem('studyai_lang');
  if (saved && translations[saved]) return saved;

  const langs = navigator.languages || [navigator.language || 'fr'];
  for (const l of langs) {
    // Try full locale first (e.g. pt-BR), then base code (e.g. pt)
    const full = l.toLowerCase();
    if (translations[full]) return full;
    const base = full.split('-')[0];
    if (translations[base]) return base;
  }
  return 'fr';
}

let currentLang = detectLang();

// Traduit une clé avec interpolation de variables
// t('quiz_counter', { c: 2, t: 5 }) → "Question 2 / 5"
function t(key, vars = {}) {
  const dict = translations[currentLang] || translations.fr;
  const str  = dict[key] ?? translations.fr[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
}

// Applique les traductions aux éléments data-i18n du DOM
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.documentElement.lang = currentLang;
  document.documentElement.dir  = currentLang === 'ar' ? 'rtl' : 'ltr';
}

// Change la langue active et retraduit tout
function setLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('studyai_lang', lang);
  applyTranslations();
  document.dispatchEvent(new CustomEvent('langchange'));
  // Toast confirmation
  const msg = t('toast_lang_changed');
  if (window.showToast) {
    window.showToast(msg);
  } else {
    const el = document.createElement('div');
    el.textContent = msg;
    el.style.cssText = 'position:fixed;bottom:80px;left:50%;transform:translateX(-50%);background:#7c3aed;color:#fff;padding:8px 18px;border-radius:20px;font-size:14px;z-index:99999;pointer-events:none;opacity:1;transition:opacity .4s';
    document.body.appendChild(el);
    setTimeout(() => { el.style.opacity = '0'; setTimeout(() => el.remove(), 400); }, 2000);
  }
}

// Expose l'API globale : window.i18n.t(), window.i18n.setLang()
window.i18n = {
  t,
  setLang,
  applyTranslations,
  get currentLang() { return currentLang; },
  get langs() { return Object.keys(translations); },
};
